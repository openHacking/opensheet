export const functionDefinitions: readonly FunctionDefinition[] = Object.freeze(
  definitionsInput.map(([name, minArgs, maxArgs, signature, evaluation, description]) =>
    Object.freeze({ name, minArgs, maxArgs, signature, evaluation, description }),
  ),
);
const definitions = new Map(functionDefinitions.map((definition) => [definition.name, definition]));
export const supportedFunctions: readonly string[] = Object.freeze(
  functionDefinitions.map(({ name }) => name),
);
export function functionDefinition(name: string): FunctionDefinition | undefined {
  return definitions.get(name);
}
